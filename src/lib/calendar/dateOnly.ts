/**
 * Calendar all-day events represent a civil date, not a moment in time.
 * Using UTC components keeps that date stable when a server and browser use
 * different timezones or when a recurring series crosses a DST boundary.
 */
export function dateOnlyKeyFromUtc(date: Date): string {
  return [
    date.getUTCFullYear(),
    String(date.getUTCMonth() + 1).padStart(2, '0'),
    String(date.getUTCDate()).padStart(2, '0'),
  ].join('-');
}

/** Converts YYYY-MM-DD into midnight in the viewer's local timezone. */
export function localDateFromDateOnlyKey(value: string): Date | null {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  if (!match) return null;

  const year = Number(match[1]);
  const monthIndex = Number(match[2]) - 1;
  const day = Number(match[3]);
  const date = new Date(year, monthIndex, day);
  if (
    date.getFullYear() !== year ||
    date.getMonth() !== monthIndex ||
    date.getDate() !== day
  ) {
    return null;
  }
  return date;
}
